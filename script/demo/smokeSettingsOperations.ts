import assert from 'node:assert/strict';
import type { Page } from 'playwright';
import type pg from 'pg';
/** CRUD only on fresh probes in the runner's disposable database. */
export async function runSettingsOperations(page: Page, db: pg.Client, userProbe: {
    id: string;
    email: string;
}) {
    const section = (key: string) => page.getByTestId(`settings-section-${key}`);
    const open = async (key: string) => {
        const t = section(key).locator('h3 > button').first();
        if (await t.getAttribute('aria-expanded') === 'false')
            await t.click();
    };
    const fold = async (key: string) => { const t = section(key).locator('h3 > button').first(); await t.click(); await t.click(); };
    const response = (method: string, path: string) => page.waitForResponse(r => new URL(r.url()).pathname === path && r.request().method() === method);
    const confirm = async () => page.getByRole('alertdialog').getByRole('button', { name: 'Eliminar', exact: true }).click();
    const result: any[] = [];
    await page.getByRole('tab', { name: /producción|production/i }).click();
    await open('people');
    const people = section('people');
    await people.getByRole('textbox').first().fill('UI03C CRUD person');
    const added = response('POST', '/api/staff-people');
    await people.getByRole('button', { name: /añadir|add/i, exact: true }).click();
    const created = await added;
    assert.equal(created.status(), 201);
    const person = await created.json();
    const row = people.getByRole('row').filter({ hasText: 'UI03C CRUD person' });
    const editingRow = people.getByRole('row').filter({ has: page.getByRole('button', { name: 'Cancelar', exact: true }) });
    await row.getByRole('button', { name: 'Editar', exact: true }).click();
    await editingRow.getByRole('textbox').fill('UI03C cancelled');
    await fold('people');
    assert.equal(await editingRow.getByRole('textbox').inputValue(), 'UI03C cancelled');
    await editingRow.getByRole('button', { name: 'Cancelar', exact: true }).click();
    assert.equal(await editingRow.getByRole('textbox').count(), 0);
    await row.getByRole('button', { name: 'Editar', exact: true }).click();
    await editingRow.getByRole('textbox').fill('UI03C CRUD person edited');
    await fold('people');
    const edit = response('PATCH', `/api/staff-people/${person.id}`);
    await editingRow.getByRole('button', { name: 'Guardar', exact: true }).click();
    assert.equal((await edit).status(), 200);
    assert.equal((await db.query('SELECT name FROM public.staff_people WHERE id=$1', [person.id])).rows[0].name, 'UI03C CRUD person edited');
    await row.getByRole('button', { name: 'Eliminar', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
    assert.equal((await db.query('SELECT count(*)::int AS n FROM public.staff_people WHERE id=$1', [person.id])).rows[0].n, 1);
    await row.getByRole('button', { name: 'Eliminar', exact: true }).click();
    const removed = response('DELETE', `/api/staff-people/${person.id}`);
    await confirm();
    assert.equal((await removed).status(), 200);
    result.push({ surface: 'people', create: 201, edit: 200, delete: 200, cancel: true, draftRetained: true });
    await open('teams');
    const teams = section('teams');
    const fields = teams.getByRole('textbox');
    await fields.nth(0).fill('ui03c-probe');
    await fields.nth(1).fill('UI03C CRUD team');
    await fold('teams');
    assert.equal(await fields.nth(1).inputValue(), 'UI03C CRUD team');
    await teams.getByRole('checkbox',{name:/Integrante /}).first().check();
    const teamCreated = response('POST', '/api/itinerant-teams');
    await teams.getByRole('button', { name: 'Crear composición', exact: true }).click();
    const teamResponse = await teamCreated;
    assert.equal(teamResponse.status(), 201);
    const team = await teamResponse.json();
    const teamRow = teams.getByTestId('itinerant-composition').filter({hasText:'UI03C CRUD team'});
    await teamRow.getByRole('button', { name: 'Eliminar', exact: true }).click();
    const teamDeleted = response('DELETE', `/api/itinerant-teams/${team.id}`);
    await confirm();
    assert.equal((await teamDeleted).status(), 200);
    result.push({ surface: 'teams', create: 201, delete: 200, draftRetained: true });
    await page.getByRole('tab', { name: /plantillas|templates/i }).click();
    await open('templates');
    const templates = section('templates');
    await templates.getByRole('button', { name: 'Create', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByPlaceholder('Name', { exact: true }).fill('UI03C CRUD template');
    await dialog.getByPlaceholder('Abreviatura (ej. ENTR)', { exact: true }).fill('UI03C');
    await dialog.getByRole('spinbutton').first().fill('10');
    const templateCreated = response('POST', '/api/task-templates');
    await dialog.getByRole('button', { name: 'Guardar', exact: true }).click();
    const tr = await templateCreated;
    assert.equal(tr.status(), 201);
    const template = await tr.json();
    const card = templates.locator('.bg-card').filter({ has: page.getByText('UI03C CRUD template', { exact: true }) }).last();
    const editCard = templates.locator('.bg-card').filter({ has: page.getByRole('button', { name: 'Cancelar', exact: true }) }).last();
    await card.getByRole('button', { name: 'Editar', exact: true }).click();
    await editCard.getByRole('textbox').first().fill('UI03C template pending');
    await fold('templates');
    assert.equal(await templates.getByRole('textbox').first().inputValue(), 'UI03C template pending');
    await templates.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await card.getByRole('button', { name: 'Editar', exact: true }).click();
    await editCard.getByRole('spinbutton', { name: 'Margen antes (vacío = heredado)', exact: true }).fill('0');
    await fold('templates');
    const templateEdited = response('PATCH', `/api/ta/${template.id}`);
    await editCard.getByRole('button', { name: 'Guardar', exact: true }).click();
    assert.equal((await templateEdited).status(), 200);
    assert.equal((await db.query('SELECT participant_margin_before_minutes FROM public.task_templates WHERE id=$1', [template.id])).rows[0].participant_margin_before_minutes, 0);
    await card.locator('button').last().click();
    const templateDeleted = response('DELETE', `/api/task-templates/${template.id}`);
    await page.getByRole('alertdialog').getByRole('button', { name: 'Delete', exact: true }).click();
    assert.equal((await templateDeleted).status(), 200);
    result.push({ surface: 'templates', create: 201, edit: 200, delete: 200, cancel: true, draftRetained: true });
    await page.getByRole('tab', { name: /recursos|resources/i }).click();
    await open('resources');
    const resources = section('resources');
    await resources.getByRole('button', { name: 'Añadir tipo', exact: true }).click();
    const typeForm = resources.locator('.bg-card').filter({ has: page.getByText('Añadir tipo (grupo)', { exact: true }) }).last();
    await typeForm.getByPlaceholder('Cámara', { exact: true }).fill('UI03C CRUD type');
    await typeForm.getByPlaceholder('camera', { exact: true }).fill('ui03c-probe');
    await fold('resources');
    assert.equal(await typeForm.getByPlaceholder('camera', { exact: true }).inputValue(), 'ui03c-probe');
    const typeCreated = response('POST', '/api/resource-types');
    await typeForm.getByRole('button', { name: 'Crear tipo', exact: true }).click();
    const rt = await typeCreated;
    assert.equal(rt.status(), 200);
    const type = await rt.json();
    await resources.getByRole('button', { name: 'Añadir unidad', exact: true }).click();
    const itemForm = resources.locator('.bg-card').filter({ has: page.getByText('Añadir unidad (1 a 1)', { exact: true }) }).last();
    await itemForm.getByRole('combobox').click();
    await page.getByRole('option', { name: 'UI03C CRUD type', exact: true }).click();
    await itemForm.getByRole('textbox').fill('UI03C CRUD item');
    const itemCreated = response('POST', '/api/resource-items');
    await itemForm.getByRole('button', { name: 'Crear unidad', exact: true }).click();
    const ri = await itemCreated;
    assert.equal(ri.status(), 200);
    const item = await ri.json();
    await resources.getByTitle('Expandir todos', { exact: true }).click();
    const probeType = resources.locator('.bg-card').filter({ has: page.getByText('UI03C CRUD type', { exact: true }) }).last();
    const itemName = probeType.getByRole('textbox');
    await itemName.waitFor();
    await itemName.fill('UI03C CRUD item edited');
    await fold('resources');
    assert.equal(await itemName.inputValue(), 'UI03C CRUD item edited');
    const renamed = response('PATCH', `/api/resource-items/${item.id}`);
    await itemName.press('Tab');
    const rename = await renamed;
    assert.equal(rename.status(), 200);
    assert.deepEqual(rename.request().postDataJSON(), { name: 'UI03C CRUD item edited' });
    const itemRow = itemName.locator('..');
    await itemRow.getByRole('button', { name: 'Componentes', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
    await itemRow.getByRole('button', { name: 'Eliminar', exact: true }).click();
    const itemDeleted = response('DELETE', `/api/resource-items/${item.id}`);
    await confirm();
    assert.equal((await itemDeleted).status(), 200);
    const typeCard = resources.locator('.bg-card').filter({ has: page.getByText('UI03C CRUD type', { exact: true }) }).last();
    await typeCard.getByRole('button', { name: 'Eliminar', exact: true }).click();
    const typeDeleted = response('DELETE', `/api/resource-types/${type.id}`);
    await confirm();
    assert.equal((await typeDeleted).status(), 200);
    result.push({ surface: 'resources', typeCreate: 200, itemCreate: 200, rename: 200, itemDelete: 200, typeDelete: 200, componentsDialog: true, draftRetained: true });
    assert.equal((await db.query('SELECT is_active FROM public.resource_items WHERE id=$1', [item.id])).rows[0].is_active, false);
    assert.equal((await db.query('SELECT is_active FROM public.resource_types WHERE id=$1', [type.id])).rows[0].is_active, false);
    // The product archives resources. Remove only the newly created probe rows so
    // the harness can compare its entire protected catalog literally at the end.
    await db.query('DELETE FROM public.resource_items WHERE id=$1', [item.id]);
    await db.query('DELETE FROM public.resource_types WHERE id=$1', [type.id]);
    await page.getByRole('tab', { name: /platós|spaces/i }).click();
    await open('spaces');
    const zones = section('spaces');
    await zones.getByRole('button', { name: 'Crear nuevo plató', exact: true }).click();
    await zones.getByPlaceholder('Ej. Plató 7', { exact: true }).fill('UI03C CRUD zone');
    await fold('spaces');
    const zoneCreated = response('POST', '/api/zones');
    await zones.getByRole('button', { name: 'Crear', exact: true }).click();
    const zr = await zoneCreated;
    assert.ok(zr.ok());
    const zoneData = await zr.json();
    const zone = zones.locator('div.rounded-lg.p-3').filter({ has: page.getByText('UI03C CRUD zone', { exact: true }) }).last();
    await zone.getByRole('button', { name: 'Edit', exact: true }).click();
    const zoneEditor = zones.locator('div.rounded-lg.p-3').filter({ has: page.getByRole('button', { name: 'Save', exact: true }) }).last();
    await zoneEditor.getByRole('textbox').first().fill('UI03C CRUD zone edited');
    await fold('spaces');
    assert.equal(await zoneEditor.getByRole('textbox').first().inputValue(), 'UI03C CRUD zone edited');
    const zoneSaved = response('PATCH', `/api/zones/${zoneData.id}`);
    await zoneEditor.getByRole('button', { name: 'Save', exact: true }).click();
    assert.ok((await zoneSaved).ok());
    const editedZone = zones.locator('div.rounded-lg.p-3').filter({ has: page.getByText('UI03C CRUD zone edited', { exact: true }) }).last();
    page.once('dialog', d => d.accept('UI03C CRUD space'));
    const spaceCreated = response('POST', '/api/spaces');
    await editedZone.getByRole('button', { name: '+ Espacio raíz', exact: true }).click();
    const sr = await spaceCreated;
    assert.ok(sr.ok());
    const spaceData = await sr.json();
    const spaceRow = editedZone.getByText('UI03C CRUD space', { exact: true }).locator('..');
    await spaceRow.getByRole('button', { name: 'Edit', exact: true }).click();
    await editedZone.getByRole('textbox').fill('UI03C space cancelled');
    await fold('spaces');
    assert.equal(await editedZone.getByRole('textbox').inputValue(), 'UI03C space cancelled');
    await editedZone.getByRole('button', { name: 'Cancel', exact: true }).click();
    await spaceRow.getByRole('button', { name: 'Edit', exact: true }).click();
    await editedZone.getByRole('textbox').fill('UI03C CRUD space edited');
    await fold('spaces');
    const spaceSaved = response('PATCH', `/api/spaces/${spaceData.id}`);
    await editedZone.getByRole('button', { name: 'Save', exact: true }).click();
    assert.ok((await spaceSaved).ok());
    await editedZone.getByTitle('Eliminar espacio', { exact: true }).click();
    const spaceDeleted = response('DELETE', `/api/spaces/${spaceData.id}`);
    await confirm();
    assert.ok((await spaceDeleted).ok());
    await editedZone.getByTitle('Eliminar plató', { exact: true }).click();
    const zoneDeleted = response('DELETE', `/api/zones/${zoneData.id}`);
    await confirm();
    assert.ok((await zoneDeleted).ok());
    result.push({ surface: 'zones-spaces', create: true, edit: true, delete: true, cancel: true, draftRetained: true });
    await page.getByRole('tab', { name: /usuarios/i }).click();
    await open('users');
    const userRow = section('users').getByRole('row').filter({ hasText: userProbe.email });
    await userRow.getByRole('combobox').first().click();
    await page.getByRole('option', { name: 'aux', exact: true }).click();
    await fold('users');
    assert.equal(await userRow.getByRole('combobox').first().textContent(), 'aux');
    const userSaved = response('PATCH', `/api/admin/users/${userProbe.id}/role`);
    await userRow.getByRole('button', { name: 'Guardar', exact: true }).click();
    const ur = await userSaved;
    assert.ok(ur.ok());
    assert.deepEqual(ur.request().postDataJSON(), { roleKey: 'aux' });
    await section('users').getByRole('status').waitFor({ state: 'hidden' });
    await userRow.getByTitle('Eliminar usuario', { exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
    await userRow.getByTitle('Eliminar usuario', { exact: true }).click();
    const userDeleted = response('DELETE', `/api/admin/users/${userProbe.id}`);
    await confirm();
    assert.ok((await userDeleted).ok());
    assert.equal((await db.query('SELECT count(*)::int AS n FROM auth.users WHERE id=$1', [userProbe.id])).rows[0].n, 0);
    result.push({ surface: 'users', roleSave: true, delete: true, deleteCancel: true, draftRetained: true });
    return result;
}
